    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if vals.get('name', 'New') == 'New':
                month = vals.get('period_month', '1')
                year = vals.get('period_year', '2026')
                vals['name'] = f'SAS/{year}/{month.zfill(2)}'
        return super().create(vals_list)
    
    @api.depends('period_month', 'period_year')
    def _compute_display_name(self):
        months = dict(self._fields['period_month'].selection)
        for rec in self:
            month_name = months.get(rec.period_month, rec.period_month)
            rec.display_name = f'Stock Accuracy Scorecard: {month_name} {rec.period_year}'
    
    @api.depends('accuracy_line_ids.is_accurate')
    def _compute_accuracy_metrics(self):
        """AUTO-055: Calculate overall accuracy score (FR-REP-003)."""
        for rec in self:
            lines = rec.accuracy_line_ids
            rec.total_items_counted = len(lines)
            
            if rec.total_items_counted > 0:
                rec.items_accurate = len(lines.filtered('is_accurate'))
                rec.items_with_variance = rec.total_items_counted - rec.items_accurate
                rec.accuracy_score = (rec.items_accurate / rec.total_items_counted) * 100.0
            else:
                rec.items_accurate = 0
                rec.items_with_variance = 0
                rec.accuracy_score = 0.0
            
            _logger.info(
                f'AUTO-055: Stock accuracy calculated for {rec.period_month}/{rec.period_year} - '
                f'Score: {rec.accuracy_score:.1f}%, {rec.items_accurate}/{rec.total_items_counted} items accurate'
            )
    
    @api.depends('accuracy_score')
    def _compute_accuracy_rating(self):
        """AUTO-055: Classify accuracy into rating bands."""
        for rec in self:
            score = rec.accuracy_score
            if score >= 98:
                rec.accuracy_rating = 'excellent'
            elif score >= 95:
                rec.accuracy_rating = 'good'
            elif score >= 90:
                rec.accuracy_rating = 'fair'
            else:
                rec.accuracy_rating = 'poor'
    
    @api.depends('accuracy_line_ids.variance_quantity', 'accuracy_line_ids.variance_value')
    def _compute_variance_analysis(self):
        """Calculate total variance quantities and values."""
        for rec in self:
            rec.total_variance_quantity = sum(abs(line.variance_quantity) for line in rec.accuracy_line_ids)
            rec.total_variance_value = sum(abs(line.variance_value) for line in rec.accuracy_line_ids)
    
    @api.depends('accuracy_line_ids.variance_percentage')
    def _compute_top_discrepancies(self):
        """Identify top 10 items with largest variance for investigation."""
        for rec in self:
            # Sort by absolute variance percentage descending
            top_lines = rec.accuracy_line_ids.sorted(
                key=lambda l: abs(l.variance_percentage),
                reverse=True
            )[:10]
            
            if top_lines:
                summary = 'Top 10 Items Requiring Investigation:\n'
                for idx, line in enumerate(top_lines, 1):
                    summary += f'{idx}. {line.item_code} - {line.item_name}: {line.variance_percentage:+.1f}% variance\n'
                rec.top_10_discrepancies = summary
            else:
                rec.top_10_discrepancies = 'No discrepancies found.'
    
    @api.depends('accuracy_score', 'period_month', 'period_year')
    def _compute_trend(self):
        """AUTO-055: Calculate trend vs previous month for continuous improvement tracking."""
        for rec in self:
            # Find previous month's scorecard
            current_month = int(rec.period_month)
            current_year = int(rec.period_year)
            
            if current_month == 1:
                prev_month = 12
                prev_year = current_year - 1
            else:
                prev_month = current_month - 1
                prev_year = current_year
            
            previous_scorecard = self.search([
                ('period_month', '=', str(prev_month)),
                ('period_year', '=', str(prev_year)),
                ('state', 'in', ['calculated', 'reviewed']),
            ], limit=1)
            
            if previous_scorecard:
                rec.previous_month_score = previous_scorecard.accuracy_score
                rec.trend_change = rec.accuracy_score - previous_scorecard.accuracy_score
                
                # Determine trend direction
                if rec.trend_change >= 2.0:
                    rec.trend_direction = 'improving'
                elif rec.trend_change <= -2.0:
                    rec.trend_direction = 'declining'
                else:
                    rec.trend_direction = 'stable'
            else:
                rec.previous_month_score = 0.0
                rec.trend_change = 0.0
                rec.trend_direction = 'stable'
    
