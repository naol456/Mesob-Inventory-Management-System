    @api.model
    def _cron_generate_monthly_scorecard(self):
        """AUTO-055: Cron job to auto-generate monthly stock accuracy scorecard.
        
        Runs on 1st of each month to generate scorecard for previous month.
        """
        try:
            # Calculate previous month
            today = fields.Date.today()
            if today.month == 1:
                prev_month = 12
                prev_year = today.year - 1
            else:
                prev_month = today.month - 1
                prev_year = today.year
            
            # Check if scorecard already exists for previous month
            existing = self.search([
                ('period_month', '=', str(prev_month)),
                ('period_year', '=', str(prev_year)),
            ])
            
            if existing:
                _logger.info(
                    f'AUTO-055 Cron: Scorecard already exists for {prev_month}/{prev_year} - Skipping'
                )
                return
            
            # Create new scorecard
            scorecard = self.create({
                'period_month': str(prev_month),
                'period_year': str(prev_year),
                'scorecard_date': today,
            })
            
            # Calculate scorecard from stock taking data
            scorecard.action_calculate_scorecard()
            
            # Send notification to PAO
            pao_users = self.env.ref('mesob_inventory_base.group_mesob_pao').users
            
            if pao_users:
                scorecard.message_post(
                    body=f'''<div style="background-color: #fff3cd; padding: 15px; border-left: 4px solid #ffc107;">
                        <h3>📊 Monthly Stock Accuracy Scorecard Generated</h3>
                        <p><strong>Period:</strong> {dict(self._fields['period_month'].selection).get(str(prev_month))} {prev_year}</p>
                        <p><strong>Accuracy Score:</strong> {scorecard.accuracy_score:.1f}% ({dict(self._fields['accuracy_rating'].selection).get(scorecard.accuracy_rating)})</p>
                        <p><strong>Items with Variance:</strong> {scorecard.items_with_variance}</p>
                        <p><em>Auto-generated by AUTO-055 cron job on {today}</em></p>
                        <p><strong>Action Required:</strong> Please review scorecard and investigate top discrepancies.</p>
                    </div>''',
                    subject=f'Monthly Stock Accuracy Scorecard: {prev_month}/{prev_year}',
                    partner_ids=pao_users.mapped('partner_id').ids,
                )
            
            _logger.info(
                f'AUTO-055 Cron: Generated scorecard for {prev_month}/{prev_year} - '
                f'Score: {scorecard.accuracy_score:.1f}%, {scorecard.items_with_variance} discrepancies'
            )
            
        except Exception as e:
            _logger.error(f'AUTO-055 Cron: Failed to generate monthly scorecard: {e}', exc_info=True)
            # Don't raise - allow cron to continue running


