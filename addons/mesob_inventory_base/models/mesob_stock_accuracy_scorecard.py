    def action_pao_review(self):
        """PAO reviews and acknowledges accuracy scorecard."""
        self.ensure_one()
        
        if self.state != 'calculated':
            raise ValidationError('Please calculate scorecard before reviewing.')
        
        self.state = 'reviewed'
        
        self.message_post(
            body=f'''<div style="background-color: #e7f3ff; padding: 15px; border-left: 4px solid #2196f3;">
                <h3>✅ Stock Accuracy Scorecard Reviewed</h3>
                <p><strong>Period:</strong> {dict(self._fields['period_month'].selection).get(self.period_month)} {self.period_year}</p>
                <p><strong>Accuracy Score:</strong> {self.accuracy_score:.1f}% ({dict(self._fields['accuracy_rating'].selection).get(self.accuracy_rating)})</p>
                <p><strong>Items with Variance:</strong> {self.items_with_variance}</p>
                <p><em>Reviewed by: {self.env.user.name} on {fields.Date.today()}</em></p>
            </div>''',
            subject='Stock Accuracy Scorecard Reviewed',
        )
        
