        """AUTO-035: Calculate reconciliation statistics."""
        for rec in self:
            lines = rec.reconciliation_line_ids
            rec.total_pos = len(lines)
            
            if rec.total_pos > 0:
                rec.total_reconciled = len(lines.filtered('is_fully_reconciled'))
                rec.total_discrepancies = len(lines.filtered(lambda l: not l.is_fully_reconciled))
                rec.reconciliation_rate = (rec.total_reconciled / rec.total_pos) * 100.0
                
