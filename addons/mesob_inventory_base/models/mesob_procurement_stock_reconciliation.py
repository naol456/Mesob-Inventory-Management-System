class MesobProcurementStockReconciliationLine(models.Model):
    """AUTO-035: Individual PO line reconciliation."""
    
    _name = 'mesob.procurement.stock.reconciliation.line'
    _description = 'Procurement-Stock Reconciliation Line'
    _order = 'po_reference, item_code'
    
    reconciliation_id = fields.Many2one(
        'mesob.procurement.stock.reconciliation',
        string='Reconciliation',
        required=True,
        ondelete='cascade'
    )
    
    # PO Data
    po_reference = fields.Char(string='PO Reference', required=True)
    supplier_id = fields.Many2one('res.partner', string='Supplier')
    item_code = fields.Char(string='Item Code', required=True)
    item_name = fields.Char(string='Item Name', required=True)
    po_quantity = fields.Float(string='PO Quantity', digits='Product Unit of Measure')
    po_unit_cost = fields.Monetary(string='PO Unit Cost', currency_field='currency_id')
    
    # Model 19 Data
    model19_reference = fields.Char(string='Model 19 Reference')
    model19_quantity = fields.Float(string='Model 19 Received Qty', digits='Product Unit of Measure')
    
    # Bin Card Data
    bin_card_quantity = fields.Float(string='Bin Card Debit Qty', digits='Product Unit of Measure')
    
    # Stock Record Card Data
    stock_record_reference = fields.Char(string='Stock Record Reference')
    stock_record_quantity = fields.Float(string='Stock Record Debit Qty', digits='Product Unit of Measure')
    stock_record_unit_cost = fields.Monetary(string='Stock Record Unit Cost', currency_field='currency_id')
    
    # Payment Data
    payment_reference = fields.Char(string='Payment Reference')
    payment_quantity = fields.Float(string='Paid Quantity', digits='Product Unit of Measure')
    payment_amount = fields.Monetary(string='Payment Amount', currency_field='currency_id')
    
    currency_id = fields.Many2one('res.currency', string='Currency', default=lambda self: self.env.company.currency_id)
    
    # Gap Detection (AUTO-035)
    has_quantity_gap = fields.Boolean(
        string='Quantity Gap',
        compute='_compute_gaps',
        store=True,
        help='PO qty ≠ Model 19 qty OR Model 19 qty ≠ Stock Record qty'
    )
    has_cost_gap = fields.Boolean(
        string='Cost Gap',
        compute='_compute_gaps',
        store=True,
        help='PO unit cost ≠ Stock Record unit cost'
    )
    has_payment_gap = fields.Boolean(
        string='Payment Gap',
        compute='_compute_gaps',
        store=True,
        help='Payment qty ≠ Model 19 qty'
    )
    is_fully_reconciled = fields.Boolean(
        string='Fully Reconciled',
        compute='_compute_gaps',
        store=True,
        help='No gaps detected across entire flow'
    )
    
    gap_description = fields.Text(
        string='Gap Description',
        compute='_compute_gaps',
        store=True,
        help='Detailed description of detected gaps'
    )
    
    @api.depends('po_quantity', 'model19_quantity', 'stock_record_quantity', 'payment_quantity',
                 'po_unit_cost', 'stock_record_unit_cost')
    def _compute_gaps(self):
        """AUTO-035: Detect gaps between PO → Model19 → Stock → Payment."""
        for line in self:
            gaps = []
            
            # Quantity gap detection (tolerance: 0.01 for floating point)
            tolerance = 0.01
            
            # PO vs Model 19
            if abs(line.po_quantity - line.model19_quantity) > tolerance:
                gaps.append(f'PO ordered {line.po_quantity:.2f} but Model 19 received {line.model19_quantity:.2f}')
                line.has_quantity_gap = True
            else:
                line.has_quantity_gap = False
            
            # Model 19 vs Stock Record
            if abs(line.model19_quantity - line.stock_record_quantity) > tolerance:
                gaps.append(f'Model 19 received {line.model19_quantity:.2f} but Stock Record shows {line.stock_record_quantity:.2f}')
                line.has_quantity_gap = True
            
            # Cost gap detection (tolerance: 1.0 ETB for currency rounding)
            if abs(line.po_unit_cost - line.stock_record_unit_cost) > 1.0:
                gaps.append(f'PO unit cost ETB {line.po_unit_cost:.2f} but Stock Record shows ETB {line.stock_record_unit_cost:.2f}')
                line.has_cost_gap = True
            else:
                line.has_cost_gap = False
            
            # Payment gap detection
            if abs(line.model19_quantity - line.payment_quantity) > tolerance:
                gaps.append(f'Model 19 received {line.model19_quantity:.2f} but payment processed for {line.payment_quantity:.2f}')
                line.has_payment_gap = True
            else:
                line.has_payment_gap = False
            
            # Fully reconciled if no gaps
            line.is_fully_reconciled = not (line.has_quantity_gap or line.has_cost_gap or line.has_payment_gap)
            line.gap_description = '\n'.join(gaps) if gaps else 'Fully reconciled - no discrepancies'
